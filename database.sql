CREATE TABLE IF NOT EXISTS categories (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, category_id INT NOT NULL,
 name VARCHAR(150) NOT NULL, price DECIMAL(10,2) NOT NULL DEFAULT 0,
 picture VARCHAR(255) DEFAULT NULL,
 FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(150) UNIQUE NOT NULL, password VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS students (
 id INT PRIMARY KEY, name VARCHAR(100) NOT NULL, course VARCHAR(100) NOT NULL
